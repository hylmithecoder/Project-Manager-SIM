import fs from "node:fs";
import path from "node:path";

const MIME_BY_EXT: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".txt": "text/plain; charset=utf-8",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
};

function getMimeType(filePath: string): string {
  const ext = path.extname(filePath).toLowerCase();
  return MIME_BY_EXT[ext] || "application/octet-stream";
}

function walkFiles(dir: string, baseDir = dir): string[] {
  const results: string[] = [];
  if (!fs.existsSync(dir)) return results;

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...walkFiles(fullPath, baseDir));
    } else if (entry.isFile()) {
      results.push(fullPath);
    }
  }
  return results;
}

function embedOutDir(): void {
  const outDir = path.resolve(process.cwd(), "out");
  if (!fs.existsSync(outDir)) {
    throw new Error(
      `Static export directory not found at ${outDir}. Run "STATIC_EXPORT=true bun run next build" first.`,
    );
  }

  const files = walkFiles(outDir);
  const assets: Record<string, { mime: string; base64: string }> = {};

  for (const file of files) {
    const rel = "/" + path.relative(outDir, file).split(path.sep).join("/");
    const content = fs.readFileSync(file);
    assets[rel] = {
      mime: getMimeType(file),
      base64: content.toString("base64"),
    };
  }

  const targetFile = path.resolve(process.cwd(), "server/embedded-assets.ts");
  const outputCode = `export interface EmbeddedAsset {
  mime: string;
  base64: string;
}

// Auto-generated by server/scripts/embed-static.ts — embeds ${files.length} Next.js static export files
export const EMBEDDED_ASSETS: Record<string, EmbeddedAsset> = ${JSON.stringify(assets, null, 2)};
`;

  fs.writeFileSync(targetFile, outputCode, "utf8");
  console.log(
    `[embed-static] Embedded ${files.length} frontend files from out/ into server/embedded-assets.ts`,
  );
}

if (import.meta.main) {
  embedOutDir();
}
